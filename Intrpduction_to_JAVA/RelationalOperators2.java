package Intrpduction_to_JAVA;

public class RelationalOperators2 {
    public static void main(String[] args) {
        
        //RELATIONAL OPERATORS IN BOOLEAN

        int num1 = 20;
        int num2 = 89;

        boolean a = num1 == num2;
        boolean b = num1 != num2;
        boolean c = num1 > num2;
        boolean d = num1 < num2;
        boolean e = num1 >= num2;
        boolean f = num1 <= num2;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
    }
}
