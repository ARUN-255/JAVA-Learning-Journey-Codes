package Intrpduction_to_JAVA;

public class RelationalOperators3 {
    public static void main(String[] args) {
        
        //CODE DIRECT PRINTING

        int num1 = 23;
        int num2 = 64;

        System.out.println(num1 == num2);
        System.out.println(num1 != num2);
        System.out.println(num1 >= num2);
        System.out.println(num1 <= num2);
        System.out.println(num1 > num2);
        System.out.println(num1 < num2);
    }
}
