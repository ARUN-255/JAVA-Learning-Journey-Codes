package Intrpduction_to_JAVA;

public class AssignmentOperators2 {
    public static void main(String[] args) {
        
        //THE NORMAL ASSIGNMENT OPERATORS PROGRAM CAN BE WRITTEN EVEN SMALLER
        int num1 = 100;
        int num2 = 50;

        System.out.println(num1+num2);
        System.out.println(num1-num2);
        System.out.println(num1*num2);
        System.out.println(num1/num2);
        System.out.println(num1%num2);
    }
}
