package Intrpduction_to_JAVA;

public class DoWhileLoops {
    public static void main(String[] args) {

        // DO WHILE LOOP
        // FIRST THE CODE OF BLOCK IS EXECUTED THEN ONLY THE CONDITION IS CHECKED
        
        int i = 1;

        do{
            System.out.println("The count is : "+i);
            i++;
        }while(i<=10);
    }
}
