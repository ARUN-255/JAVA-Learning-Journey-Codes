package Intrpduction_to_JAVA;

public class IncrementAndDecrement {
    public static void main(String[] args) {
        
        int num = 20;

        //SUFFIC
        System.out.println(num++); //20
        System.out.println(num); //21

        //PREFIC

        System.out.println(++num); //22

    }
}
