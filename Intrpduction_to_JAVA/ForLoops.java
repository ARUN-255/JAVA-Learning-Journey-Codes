package Intrpduction_to_JAVA;

public class ForLoops {
    public static void main(String[] args) {
        //FOR LOOPS
        //IT IS ONE THE MOST USED LOOPS , IT DOES NOT REPLICATE THE DO WHILE OR WHILE LOOP BUT IT HAS ALL THREE MAJOR PILLARS OF LOOPS IN ONE SINGLE LINE

        for( int i=1 ; i<=100 ; i++ ){
            System.out.println("The count is : "+i);
        }
    }
}
