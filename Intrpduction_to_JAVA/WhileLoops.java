package Intrpduction_to_JAVA;

public class WhileLoops {
    public static void main(String[] args) {
        // A LOOP REPEATS A CODE OF BLOCKS MULTIPLE TIMES UNTILL THE CONDITION IS SATISFIED
        //WHILE LOOP
        //FIRST THE CONDITION IS CHECKED THEN THE CODE OF BLOCK IS EXECUTED
        
        int i = 1;

        while(i<=10){
            System.out.println("The count is : "+i);
            i++;
        }
    }
}
