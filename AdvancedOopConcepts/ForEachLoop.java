package AdvancedOopConcepts;



public class ForEachLoop {
    public static void main(StringDemo[] args) {
        
        int nums[] = new int[4];
    
            nums[0] = 12;
            nums[1] = 14;
            nums[2] = 19;
            nums[3] = 27;

            for(int n : nums){
                System.out.println(n);
            }

        
        


    }

}
